module hornero_core

fn test_assistant_knowledge_markdown_shape() {
	md := assistant_knowledge_markdown('horneroctl-test', '2026-10-21 10:00',
		'system_info -> horneroctl system info --json; package_updates -> horneroctl package updates --json')
	assert md.starts_with('# HorneroOS assistant knowledge')
	assert md.contains('Generated by horneroctl-test at 2026-10-21 10:00')
	assert md.contains('- `system_info` — `horneroctl system info --json`')
	assert md.contains('- `package_updates` — `horneroctl package updates --json`')
	assert md.contains('never auto-answered')
	assert !md.contains('assistant.key')
}

fn test_assistant_knowledge_markdown_is_bounded() {
	mut tools := []string{}
	for i in 0 .. 400 {
		tools << 'tool_${i} -> horneroctl system info --json'
	}
	md := assistant_knowledge_markdown('horneroctl-test', 'now', tools.join('; '))
	assert md.len <= assistant_knowledge_max_chars
	assert md.contains('truncated')
}

fn test_assistant_setup_plan_is_pinned_and_safe() {
	plan := assistant_setup_plan('/home/user/.local/bin/hermes')
	joined := plan.join('\n')
	assert joined.contains(assistant_hermes_repo_url)
	assert joined.contains(assistant_studied_hermes_commit)
	assert joined.contains('0600')
	assert joined.contains('assistant gateway start --yes')
	assert joined.contains('/home/user/.local/bin/hermes')
	assert !joined.contains('curl')
	assert !joined.contains('sudo')
}

fn test_assistant_setup_paths() {
	assert assistant_hermes_src_dir().ends_with('hornero/hermes/src')
	assert assistant_skill_file().ends_with('.hermes/skills/hornero/SKILL.md')
	assert assistant_hermes_wrapper().ends_with('.local/bin/hermes')
}

fn test_assistant_embedded_skill_is_the_hornero_skill() {
	skill := assistant_skill_markdown()
	assert skill.contains('name: hornero')
	assert skill.contains('horneroctl assistant tools --json')
	assert skill.contains('auto-answer an approval')
}
