module hornero_core

import os

fn vault_test_sources() KnowledgeVaultSources {
	return KnowledgeVaultSources{
		system:       {
			'edition': 'hornero-test'
			'kernel':  'test-kernel'
		}
		desktop:      {
			'activeCompositor': 'niri'
		}
		packages:     {
			'packageSets': 'base,desktop'
		}
		services:     {
			'assistantEnabled': 'false'
		}
		capabilities: {
			'tools': 'system_info -> horneroctl system info --json'
		}
		agents:       {
			'default': 'assistant disabled by default'
		}
	}
}

fn vault_test_dir(name string) string {
	dir := os.join_path(os.temp_dir(), 'hornero-vault-${name}-${os.getpid()}')
	os.rmdir_all(dir) or {}
	return dir
}

fn test_knowledge_vault_generate_writes_bounded_provenance_snapshot() {
	dir := vault_test_dir('gen')
	defer {
		os.rmdir_all(dir) or {}
	}
	write := knowledge_vault_generate_at(dir, vault_test_sources(), 'test-cli 1.0',
		'2026-01-01 00:00:00') or { panic(err) }
	assert write.files.len == knowledge_vault_sections.len
	assert write.changed
	for section in knowledge_vault_sections {
		body := os.read_file(os.join_path(dir, 'generated', '${section}.md')) or { panic(err) }
		assert body.contains('Generated by test-cli 1.0 at 2026-01-01 00:00:00')
		assert body.contains(knowledge_vault_schema)
		assert body.len <= knowledge_vault_max_section_chars + 80
	}
	manifest := os.read_file(os.join_path(dir, 'manifest.json')) or { panic(err) }
	assert manifest.contains('"schema": "hornero.knowledge-vault/v1"')
	assert manifest.contains('"sourcesHash"')
	status := knowledge_vault_check(dir, vault_test_sources())
	assert status.exists && status.fresh
	assert status.generated_by == 'test-cli 1.0'
}

fn test_knowledge_vault_no_secrets_and_bounded_render() {
	mut sources := vault_test_sources()
	sources.system['apiKey'] = 'supersecretvalue'
	sources.system['note'] = 'token=abc123 should be masked'
	sources.capabilities['tools'] = 'x'.repeat(20000)
	rendered := knowledge_vault_render_section('system', sources, 'b', 't')
	assert !rendered.contains('supersecretvalue')
	assert !rendered.contains('abc123')
	caps := knowledge_vault_render_section('capabilities', sources, 'b', 't')
	assert caps.len <= knowledge_vault_max_section_chars + 80
	assert caps.contains('truncated')
}

fn test_knowledge_vault_preserves_user_notes_and_edited_generated() {
	dir := vault_test_dir('preserve')
	defer {
		os.rmdir_all(dir) or {}
	}
	knowledge_vault_generate_at(dir, vault_test_sources(), 'b', 't1') or { panic(err) }
	note := os.join_path(dir, 'notes', 'my-note.md')
	os.write_file(note, 'my annotation\n') or { panic(err) }
	edited := os.join_path(dir, 'generated', 'system.md')
	os.write_file(edited, 'user edited this file\n') or { panic(err) }
	// Change detection must flag the edit before regeneration.
	stale := knowledge_vault_check(dir, vault_test_sources())
	assert stale.modified_files == ['system.md']
	assert !stale.fresh
	write := knowledge_vault_generate_at(dir, vault_test_sources(), 'b', 't2') or { panic(err) }
	assert write.preserved.len == 1
	assert (os.read_file(note) or { '' }) == 'my annotation\n'
	preserved := os.read_file(os.join_path(dir, 'notes', 'system.user.md')) or { panic(err) }
	assert preserved == 'user edited this file\n'
	fresh := knowledge_vault_check(dir, vault_test_sources())
	assert fresh.fresh
}

fn test_knowledge_vault_change_detection_on_source_change() {
	dir := vault_test_dir('change')
	defer {
		os.rmdir_all(dir) or {}
	}
	assert !knowledge_vault_check(dir, vault_test_sources()).exists
	knowledge_vault_generate_at(dir, vault_test_sources(), 'b', 't') or { panic(err) }
	mut changed := vault_test_sources()
	changed.system['edition'] = 'other-edition'
	status := knowledge_vault_check(dir, changed)
	assert status.exists && !status.fresh
	assert status.modified_files.len == 0
	assert status.sources_hash != status.stored_hash
	again := knowledge_vault_generate_at(dir, vault_test_sources(), 'b', 't') or { panic(err) }
	assert !again.changed // same sources: no change detected
}

fn test_knowledge_vault_generate_requires_explicit_yes() {
	dir := vault_test_dir('gate')
	os.rmdir_all(dir) or {}
	saved := os.getenv('HORNERO_KNOWLEDGE_VAULT_DIR')
	os.setenv('HORNERO_KNOWLEDGE_VAULT_DIR', dir, true)
	defer {
		if saved.len == 0 {
			os.unsetenv('HORNERO_KNOWLEDGE_VAULT_DIR')
		} else {
			os.setenv('HORNERO_KNOWLEDGE_VAULT_DIR', saved, true)
		}
		os.rmdir_all(dir) or {}
	}
	assert knowledge_vault_dir() == dir
	denied := assistant_knowledge_vault_generate_report(false, false)
	assert !denied.ok
	assert !os.exists(dir)
	preview := assistant_knowledge_vault_generate_report(true, false)
	assert preview.ok
	assert preview.data['dryRun'] == 'true'
	assert !os.exists(os.join_path(dir, 'manifest.json'))
	written := assistant_knowledge_vault_generate_report(false, true)
	assert written.ok
	assert written.data['changed'] == 'true'
	assert os.is_file(os.join_path(dir, 'manifest.json'))
	status := assistant_knowledge_vault_status_report()
	assert status.ok && status.data['fresh'] == 'true'
}

fn test_knowledge_vault_default_dir_is_user_xdg_data() {
	saved_vault := os.getenv('HORNERO_KNOWLEDGE_VAULT_DIR')
	saved_xdg := os.getenv('XDG_DATA_HOME')
	os.unsetenv('HORNERO_KNOWLEDGE_VAULT_DIR')
	os.setenv('XDG_DATA_HOME', '/tmp/hornero-vault-xdg-test', true)
	defer {
		if saved_vault.len == 0 {
			os.unsetenv('HORNERO_KNOWLEDGE_VAULT_DIR')
		} else {
			os.setenv('HORNERO_KNOWLEDGE_VAULT_DIR', saved_vault, true)
		}
		if saved_xdg.len == 0 {
			os.unsetenv('XDG_DATA_HOME')
		} else {
			os.setenv('XDG_DATA_HOME', saved_xdg, true)
		}
	}
	assert knowledge_vault_dir() == '/tmp/hornero-vault-xdg-test/hornero/knowledge-vault'
}
