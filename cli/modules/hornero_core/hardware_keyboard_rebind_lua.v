module hornero_core

import os
import x.json2

// Lua keybinding rebinds (keybinding overlay, COMPETITIVE gap #5).
//
// The factory Lua config (HorneroOS/config) loads
// hyprland.lua.d/keybindings-overlay.lua before any bind. That loader
// translates every hl.bind/hl.unbind combo through the generated remap
// table this file writes:
//
//   ${XDG_CONFIG_HOME:-~/.config}/hypr/hornero-keybinds.lua
//   (override: HORNERO_KEYBINDS_OVERLAY_FILE)
//
// so rebinding never edits keybindings.lua or the user's
// keybindings-user.lua. Each write snapshots the previous overlay under
// ${XDG_STATE_HOME:-~/.local/state}/hornero/keybinds/undo for `rebind
// undo`, then reloads Hyprland so the change is live.

pub struct KeybindRemap {
pub:
	from string
	to   string // '' disables the bind
}

pub struct KeybindEntry {
pub:
	combo      string // what the session runs now
	original   string // as written in the config ('' for live-only binds)
	category   string
	action     string
	submap     string
	source     string // factory | personal | live
	dispatcher string
	remapped   bool
	mouse      bool
}

const keybinds_overlay_header = '-- Generated by `horneroctl hardware keyboard rebind`. Do not edit by hand:
-- use the keybinding overlay (SUPER + /), Control Center > Keybinds or
-- `horneroctl hardware keyboard rebind set|reset|undo`. Loaded as data by
-- hyprland.lua.d/keybindings-overlay.lua; personal binds belong in
-- hyprland.lua.d/keybindings-user.lua.
'

const keybinds_undo_limit = 20

fn keybinds_config_base() string {
	mut base := os.getenv('XDG_CONFIG_HOME')
	if base.len == 0 {
		base = os.join_path(os.home_dir(), '.config')
	}
	return base
}

pub fn keybinds_overlay_path() string {
	env := os.getenv('HORNERO_KEYBINDS_OVERLAY_FILE')
	if env.len > 0 {
		return env
	}
	return os.join_path(keybinds_config_base(), 'hypr', 'hornero-keybinds.lua')
}

fn keybinds_undo_dir() string {
	env := os.getenv('HORNERO_KEYBINDS_UNDO_DIR')
	if env.len > 0 {
		return env
	}
	return os.join_path(hypr_state_base(), 'hornero', 'keybinds', 'undo')
}

fn keybindings_user_lua_path() string {
	env := os.getenv('HORNERO_KEYBINDINGS_USER_LUA_FILE')
	if env.len > 0 {
		return env
	}
	return os.join_path(keybinds_config_base(), 'hypr', 'hyprland.lua.d', 'keybindings-user.lua')
}

// canonical_combo matches the Lua loader: aliased, sorted, upper-cased
// modifiers plus the lower-cased key. Used only to compare combos.
pub fn canonical_combo(raw string) string {
	// "SUPER+x" (no spaces) splits on '+' like the Lua loader does.
	spaced := if raw.contains(',') { raw } else { display_combo(raw.replace('+', ' + ')) }
	mods, key, ok := parse_combo(spaced)
	if !ok {
		return ''
	}
	k := key.to_lower()
	extra := mods.split(' + ').filter(it.len > 0).map(match it {
		'WIN', 'LOGO' { 'SUPER' }
		else { it }
	})
	mut uniq := []string{}
	for m in extra {
		if m !in uniq {
			uniq << m
		}
	}
	uniq.sort()
	if uniq.len == 0 {
		return k
	}
	return uniq.join(' + ') + ' + ' + k
}

// display_combo normalises spacing ("SUPER+x" -> "SUPER + x") while
// keeping the user's modifier order and key spelling.
fn display_combo(raw string) string {
	parts := raw.split('+').map(it.trim_space()).filter(it.len > 0)
	return parts.join(' + ')
}

fn lua_string_at(text string, marker string) string {
	idx := text.index(marker) or { return '\x00' }
	mut i := idx + marker.len
	mut out := []u8{}
	for i < text.len {
		c := text[i]
		if c == `\\` && i + 1 < text.len {
			out << text[i + 1]
			i += 2
			continue
		}
		if c == `"` {
			return out.bytestr()
		}
		out << c
		i++
	}
	return '\x00'
}

// parse_keybinds_overlay reads the remap entries this module writes
// (`{ from = "...", to = "..." },` one per line). Unknown lines are ignored.
pub fn parse_keybinds_overlay(text string) []KeybindRemap {
	mut out := []KeybindRemap{}
	for raw in text.split_into_lines() {
		line := raw.trim_space()
		if !line.starts_with('{') || !line.contains('from = "') {
			continue
		}
		from := lua_string_at(line, 'from = "')
		to := lua_string_at(line, 'to = "')
		if from == '\x00' || to == '\x00' || canonical_combo(from).len == 0 {
			continue
		}
		out << KeybindRemap{
			from: from
			to:   to
		}
	}
	return out
}

pub fn render_keybinds_overlay(remaps []KeybindRemap) string {
	mut s := keybinds_overlay_header + 'return {\n\tversion = 1,\n\tremap = {\n'
	for r in remaps {
		s += '\t\t{ from = ${hypr_lua_string(r.from)}, to = ${hypr_lua_string(r.to)} },\n'
	}
	s += '\t},\n}\n'
	return s
}

fn read_keybinds_overlay() []KeybindRemap {
	text := os.read_file(keybinds_overlay_path()) or { return [] }
	return parse_keybinds_overlay(text)
}

// remap_target returns the effective combo for an as-written combo
// ('' when disabled) and whether a remap applied.
fn remap_target(remaps []KeybindRemap, written string) (string, bool) {
	c := canonical_combo(written)
	for r in remaps {
		if canonical_combo(r.from) == c {
			return r.to, true
		}
	}
	return written, false
}

// remap_origin returns the as-written combo whose bind currently sits
// on `current` (the reverse lookup used by set).
fn remap_origin(remaps []KeybindRemap, current string) string {
	c := canonical_combo(current)
	for r in remaps {
		if r.to.len > 0 && canonical_combo(r.to) == c {
			return r.from
		}
	}
	return current
}

fn with_remap(remaps []KeybindRemap, from string, to string) []KeybindRemap {
	cf := canonical_combo(from)
	mut out := remaps.filter(canonical_combo(it.from) != cf)
	if to.len > 0 && canonical_combo(to) == cf {
		return out // back to the factory combo
	}
	out << KeybindRemap{
		from: from
		to:   to
	}
	return out
}

// modmask_mods renders a Hyprland modmask in canonical order.
pub fn modmask_mods(mask int) string {
	names := [[1, 0], [2, 1], [4, 2], [8, 3], [16, 4], [32, 5], [64, 6], [128, 7]]
	labels := ['SHIFT', 'CAPS', 'CTRL', 'ALT', 'MOD2', 'MOD3', 'SUPER', 'MOD5']
	mut mods := []string{}
	for pair in names {
		if mask & pair[0] != 0 {
			mods << labels[pair[1]]
		}
	}
	mods.sort()
	return mods.join(' + ')
}

struct LiveBind {
	combo      string
	submap     string
	dispatcher string
	mouse      bool
}

// parse_live_binds parses `hyprctl binds -j`.
fn parse_live_binds(raw string) ([]LiveBind, bool) {
	parsed := json2.decode[json2.Any](raw) or { return []LiveBind{}, false }
	mut items := []json2.Any{}
	if parsed is []json2.Any {
		items = parsed.clone()
	} else {
		return []LiveBind{}, false
	}
	mut out := []LiveBind{}
	for item in items {
		if item is map[string]json2.Any {
			key := json2_str(item, 'key')
			if key.len == 0 {
				continue
			}
			mods := modmask_mods(int(json2_f64(item, 'modmask')))
			combo := if mods.len > 0 { mods + ' + ' + key } else { key }
			mut disp := json2_str(item, 'dispatcher')
			if disp.starts_with('HL.Dispatcher(') && disp.ends_with(')') {
				disp = disp['HL.Dispatcher('.len..disp.len - 1]
			} else if disp.starts_with('function:') {
				disp = 'lua function'
			}
			out << LiveBind{
				combo:      combo
				submap:     json2_str(item, 'submap')
				dispatcher: disp
				mouse:      json2_bool(item, 'mouse')
			}
		}
	}
	return out, true
}

fn read_live_binds() ([]LiveBind, bool) {
	if os.getenv('HORNERO_KEYBINDS_NO_LIVE') == '1' {
		return []LiveBind{}, false
	}
	bin := resolve_hyprctl_bin()
	if bin.len == 0 {
		return []LiveBind{}, false
	}
	rep := run_exec(ExecSpec{
		prog:        bin
		args:        ['binds', '-j']
		timeout_sec: 5
	})
	if !rep.ok {
		return []LiveBind{}, false
	}
	return parse_live_binds(rep.output)
}

struct SourceBind {
	combo    string
	category string
	action   string
	source   string
	submap   string
	mouse    bool
}

// source_bind_of splits a rendered `[cat] MODS + key -> action` line.
fn source_bind_of(line string, submap string, source string) ?SourceBind {
	mut cat := ''
	mut body := line
	if line.starts_with('[') {
		end := line.index('] ') or { return none }
		cat = line[1..end]
		body = line[end + 2..]
	}
	arrow := body.index(' -> ') or { return none }
	combo := display_combo(body[..arrow])
	if canonical_combo(combo).len == 0 {
		return none
	}
	return SourceBind{
		combo:    combo
		category: cat
		action:   body[arrow + 4..].trim_space()
		source:   source
		submap:   submap
		mouse:    combo.contains('mouse:')
	}
}

fn source_binds_from_lines(lines []string, source string) []SourceBind {
	mut out := []SourceBind{}
	for line in lines {
		if b := source_bind_of(line, '', source) {
			out << b
		}
	}
	return out
}

fn source_binds_from_lua(text string, source string) []SourceBind {
	mut out := []SourceBind{}
	for l in parse_keybindings_lua_ctx(text) {
		if b := source_bind_of(l.line, l.submap, source) {
			out << b
		}
	}
	return out
}

fn read_source_binds() []SourceBind {
	mut out := []SourceBind{}
	factory := os.read_file(keybindings_path()) or { '' }
	out << source_binds_from_lua(factory, 'factory')
	personal := os.read_file(keybindings_user_lua_path()) or { '' }
	for b in source_binds_from_lua(personal, 'personal') {
		out << SourceBind{
			...b
			category: if b.category.len > 0 { b.category } else { 'Personal' }
		}
	}
	return out
}

fn entry_key(submap string, combo string) string {
	return submap + '|' + canonical_combo(combo)
}

// effective_source_entries applies the remaps to the as-written global
// binds (submap binds are never remapped). Later binds
// (keybindings-user.lua) replace earlier ones on the same effective
// combo, as Hyprland does after unbind/bind.
fn effective_source_entries(binds []SourceBind, remaps []KeybindRemap) []KeybindEntry {
	mut out := []KeybindEntry{}
	for b in binds {
		mut target := b.combo
		mut remapped := false
		if b.submap.len == 0 {
			target, remapped = remap_target(remaps, b.combo)
		}
		if target.len == 0 {
			continue
		}
		// Hyprland keeps every bind on a combo (they all fire) until an
		// unbind; personal files unbind before rebinding, so a personal
		// bind replaces the earlier one on its combo.
		if b.source == 'personal' {
			k := entry_key(b.submap, target)
			out = out.filter(entry_key(it.submap, it.combo) != k)
		}
		out << KeybindEntry{
			combo:    display_combo(target)
			original: b.combo
			category: b.category
			action:   b.action
			submap:   b.submap
			source:   b.source
			remapped: remapped
			mouse:    b.mouse
		}
	}
	return out
}

// keybind_entries merges the compositor's live binds (complete truth,
// including plugin and submap binds) with the config's metadata
// (category and readable action). Without a compositor it falls back
// to the config view.
pub fn keybind_entries() ([]KeybindEntry, bool) {
	remaps := read_keybinds_overlay()
	sources := effective_source_entries(read_source_binds(), remaps)
	live, ok := read_live_binds()
	if !ok {
		return sources, false
	}
	mut out := []KeybindEntry{}
	mut used := []bool{len: sources.len}
	for lb in live {
		k := entry_key(lb.submap, lb.combo)
		mut found := false
		// Each config bind explains one live bind, so two binds on one
		// combo (both fire in Hyprland) show up as two distinct entries.
		for i, s in sources {
			if !used[i] && entry_key(s.submap, s.combo) == k {
				used[i] = true
				out << KeybindEntry{
					...s
					dispatcher: lb.dispatcher
				}
				found = true
				break
			}
		}
		if !found {
			out << KeybindEntry{
				combo:      lb.combo
				category:   if lb.submap.len > 0 { 'Submap: ${lb.submap}' } else { 'Other' }
				action:     lb.dispatcher
				submap:     lb.submap
				source:     'live'
				dispatcher: lb.dispatcher
				mouse:      lb.mouse
			}
		}
	}
	return out, true
}

fn keybind_entry_json(e KeybindEntry) string {
	return '{"combo":${json2.encode(e.combo)},"original":${json2.encode(e.original)},"category":${json2.encode(e.category)},"action":${json2.encode(e.action)},"submap":${json2.encode(e.submap)},"source":${json2.encode(e.source)},"dispatcher":${json2.encode(e.dispatcher)},"remapped":${e.remapped},"mouse":${e.mouse}}'
}

fn remaps_json(remaps []KeybindRemap) string {
	return '[' + remaps.map('{"from":${json2.encode(it.from)},"to":${json2.encode(it.to)}}').join(',') + ']'
}

fn keybinds_undo_snapshots() []string {
	dir := keybinds_undo_dir()
	mut files := os.ls(dir) or { return [] }
	files = files.filter(it.ends_with('.lua'))
	files.sort()
	return files.map(os.join_path(dir, it))
}

fn keybinds_push_undo() ! {
	dir := keybinds_undo_dir()
	os.mkdir_all(dir)!
	current := os.read_file(keybinds_overlay_path()) or { '' }
	snaps := keybinds_undo_snapshots()
	mut next := 1
	if snaps.len > 0 {
		last := os.file_name(snaps[snaps.len - 1]).all_before('.lua')
		next = last.int() + 1
	}
	digits := next.str()
	name := '0'.repeat(if digits.len < 6 { 6 - digits.len } else { 0 }) + digits
	os.write_file(os.join_path(dir, '${name}.lua'), current)!
	all := keybinds_undo_snapshots()
	if all.len > keybinds_undo_limit {
		for old in all[..all.len - keybinds_undo_limit] {
			os.rm(old) or {}
		}
	}
}

fn keybinds_write_overlay(remaps []KeybindRemap) ! {
	path := keybinds_overlay_path()
	os.mkdir_all(os.dir(path))!
	tmp := path + '.tmp'
	os.write_file(tmp, render_keybinds_overlay(remaps))!
	os.mv(tmp, path)!
}

// keybinds_reload re-runs the Lua config so the overlay applies live.
fn keybinds_reload() string {
	if os.getenv('HORNERO_KEYBINDS_NO_RELOAD') == '1' {
		return 'saved; Hyprland reload skipped (HORNERO_KEYBINDS_NO_RELOAD=1)'
	}
	bin := resolve_hyprctl_bin()
	if bin.len == 0 {
		return 'saved; applies on next Hyprland start (hyprctl unavailable)'
	}
	rep := run_exec(ExecSpec{
		prog:        bin
		args:        ['reload']
		timeout_sec: 10
	})
	return if rep.ok {
		'applied live (hyprctl reload)'
	} else {
		'saved; hyprctl reload failed, applies on next Hyprland start'
	}
}

fn lua_rebind_status_report() CommandResult {
	remaps := read_keybinds_overlay()
	undo := keybinds_undo_snapshots().len
	return ok_result('hardware keyboard rebind', 'Lua session: ${remaps.len} managed rebind(s) in ${keybinds_overlay_path()}', {
		'managed':   'true'
		'format':    'lua'
		'overrides': remaps.len.str()
		'undo':      undo.str()
		'file':      keybinds_overlay_path()
		'remaps':    remaps_json(remaps)
	})
}

fn lua_rebind_list_report() CommandResult {
	entries, live := keybind_entries()
	remaps := read_keybinds_overlay()
	return ok_result('hardware keyboard rebind', '${entries.len} keybindings (${if live {
		'live from Hyprland'
	} else {
		'from config files'
	}})', {
		'count':     entries.len.str()
		'live':      live.str()
		'overrides': remaps.len.str()
		'undo':      keybinds_undo_snapshots().len.str()
		'file':      keybinds_overlay_path()
		'entries':   '[' + entries.map(keybind_entry_json(it)).join(',') + ']'
	})
}

pub struct LuaRebindSetOptions {
pub:
	old_combo string
	new_combo string
	swap      bool
	dry_run   bool
	yes       bool
}

// lua_rebind_set_report moves the global bind at old_combo (as the
// session runs it now) to new_combo. `none` disables it. A taken target
// is refused with the conflicting bind named, unless --swap.
fn lua_rebind_set_report(opts LuaRebindSetOptions) CommandResult {
	disable := opts.new_combo.trim_space().to_lower() == 'none'
	cur_old := display_combo(opts.old_combo)
	new_combo := if disable { '' } else { display_combo(opts.new_combo) }
	if canonical_combo(cur_old).len == 0 || (!disable && canonical_combo(new_combo).len == 0) {
		return rebind_fail('Could not parse combos. Example: --old "SUPER + Return" --new "SUPER + X" (or --new none)')
	}
	remaps := read_keybinds_overlay()
	entries, _ := keybind_entries()
	global := entries.filter(it.submap.len == 0)
	old_c := canonical_combo(cur_old)
	mut target := KeybindEntry{}
	mut found := false
	for e in global {
		if canonical_combo(e.combo) == old_c {
			target = e
			found = true
			break
		}
	}
	if !found {
		return rebind_fail('${cur_old} is not bound. Run: horneroctl hardware keyboard rebind list')
	}
	if target.source == 'live' {
		return rebind_fail('${cur_old} is not defined by the Hornero config (plugin or runtime bind); it cannot be moved from here.')
	}
	mut conflict := KeybindEntry{}
	mut has_conflict := false
	if !disable && canonical_combo(new_combo) != old_c {
		for e in global {
			if canonical_combo(e.combo) == canonical_combo(new_combo) {
				conflict = e
				has_conflict = true
				break
			}
		}
	}
	if has_conflict && !opts.swap {
		return CommandResult{
			command: 'hardware keyboard rebind'
			ok:      false
			message: '${new_combo} is already bound to ${conflict.action} (${conflict.category}). Pick another combo, or re-run with --swap to exchange them.'
			data:    {
				'conflict':          conflict.combo
				'conflict_action':   conflict.action
				'conflict_category': conflict.category
				'conflict_source':   conflict.source
			}
		}
	}
	if has_conflict && conflict.source == 'live' {
		return rebind_fail('${new_combo} is held by a plugin or runtime bind (${conflict.action}); it cannot be swapped.')
	}
	origin := remap_origin(remaps, cur_old)
	mut next := with_remap(remaps, origin, new_combo)
	if has_conflict {
		next = with_remap(next, remap_origin(remaps, conflict.combo), cur_old)
	}
	summary := if disable {
		'Disable ${cur_old} (${target.action})'
	} else if has_conflict {
		'Swap ${cur_old} (${target.action}) with ${new_combo} (${conflict.action})'
	} else {
		'Rebind ${cur_old} -> ${new_combo} (${target.action})'
	}
	if opts.dry_run {
		return ok_result('hardware keyboard rebind', 'Would write ${keybinds_overlay_path()}: ${summary}', {
			'dry_run': 'true'
			'old':     cur_old
			'new':     new_combo
			'swap':    has_conflict.str()
			'remaps':  remaps_json(next)
		})
	}
	if !opts.yes {
		return rebind_fail('Rebind changes live keybindings. Re-run with --yes (or --dry-run to preview).')
	}
	keybinds_push_undo() or { return rebind_fail('Could not save the undo snapshot: ${err.msg()}') }
	keybinds_write_overlay(next) or {
		return rebind_fail('Could not write ${keybinds_overlay_path()}: ${err.msg()}')
	}
	live := keybinds_reload()
	return ok_result('hardware keyboard rebind', '${summary}. ${live}. Undo: horneroctl hardware keyboard rebind undo --yes', {
		'old':       cur_old
		'new':       new_combo
		'swap':      has_conflict.str()
		'file':      keybinds_overlay_path()
		'overrides': next.len.str()
		'undo':      keybinds_undo_snapshots().len.str()
	})
}

fn lua_rebind_reset_report(dry_run bool, yes bool) CommandResult {
	remaps := read_keybinds_overlay()
	if remaps.len == 0 {
		return ok_result('hardware keyboard rebind', 'No managed rebinds; factory keybindings are already active.', {
			'overrides': '0'
		})
	}
	if dry_run {
		return ok_result('hardware keyboard rebind', 'Would remove ${remaps.len} managed rebind(s) from ${keybinds_overlay_path()}', {
			'dry_run':   'true'
			'overrides': remaps.len.str()
		})
	}
	if !yes {
		return rebind_fail('Reset removes all managed rebinds. Re-run with --yes (or --dry-run to preview).')
	}
	keybinds_push_undo() or { return rebind_fail('Could not save the undo snapshot: ${err.msg()}') }
	keybinds_write_overlay([]KeybindRemap{}) or {
		return rebind_fail('Could not write ${keybinds_overlay_path()}: ${err.msg()}')
	}
	live := keybinds_reload()
	return ok_result('hardware keyboard rebind', 'Removed ${remaps.len} managed rebind(s); factory keybindings restored. ${live}.', {
		'overrides': '0'
		'file':      keybinds_overlay_path()
		'undo':      keybinds_undo_snapshots().len.str()
	})
}

// keyboard_rebind_undo_report restores the overlay saved before the
// last set/reset/undo-able write.
pub fn keyboard_rebind_undo_report(dry_run bool, yes bool) CommandResult {
	if !hypr_lua_config_enabled() {
		return rebind_fail('Undo is available on Lua sessions (the factory config). On hyprlang configs use rebind reset.')
	}
	snaps := keybinds_undo_snapshots()
	if snaps.len == 0 {
		return rebind_fail('Nothing to undo.')
	}
	last := snaps[snaps.len - 1]
	text := os.read_file(last) or { return rebind_fail('Could not read ${last}: ${err.msg()}') }
	restored := parse_keybinds_overlay(text)
	if dry_run {
		return ok_result('hardware keyboard rebind', 'Would restore ${restored.len} managed rebind(s) from ${last}', {
			'dry_run':   'true'
			'overrides': restored.len.str()
			'remaps':    remaps_json(restored)
		})
	}
	if !yes {
		return rebind_fail('Undo changes live keybindings. Re-run with --yes (or --dry-run to preview).')
	}
	keybinds_write_overlay(restored) or {
		return rebind_fail('Could not write ${keybinds_overlay_path()}: ${err.msg()}')
	}
	os.rm(last) or {}
	live := keybinds_reload()
	return ok_result('hardware keyboard rebind', 'Undone: ${restored.len} managed rebind(s) restored. ${live}.', {
		'overrides': restored.len.str()
		'file':      keybinds_overlay_path()
		'undo':      keybinds_undo_snapshots().len.str()
	})
}

// keyboard_rebind_list_report lists every keybinding with category,
// action, submap and remap state as JSON (`data.entries`). Hyprlang
// configs report the parsed override view.
pub fn keyboard_rebind_list_report() CommandResult {
	if hypr_lua_config_enabled() {
		return lua_rebind_list_report()
	}
	_, defaults_text, user_text := rebind_read_inputs()
	mut lines := parse_keybindings_text(defaults_text)
	if user_text.trim_space().len > 0 {
		lines = apply_overrides_to_lines(lines, user_text)
	}
	entries := effective_source_entries(source_binds_from_lines(lines, 'factory'), []KeybindRemap{})
	return ok_result('hardware keyboard rebind', '${entries.len} keybindings (hyprlang config)', {
		'count':   entries.len.str()
		'live':    'false'
		'entries': '[' + entries.map(keybind_entry_json(it)).join(',') + ']'
	})
}
