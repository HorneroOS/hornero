module hornero_core

import os

// KDE colour-scheme consumer (hornero#439, part of the Qt consumer).
//
// KDE Frameworks apps (Dolphin, Kate, Okular, ...) do not take their view and
// window backgrounds from the qt6ct palette: KColorSchemeManager applies the
// scheme named by kdeglobals [UiSettings] ColorScheme and, when none is set
// outside Plasma, falls back to Breeze Light. That is why Dolphin stayed light
// even with a dark qt6ct palette. This consumer renders the live
// Signal/Chromatic scheme into an owned KDE scheme file and manages exactly one
// key of kdeglobals: [UiSettings] ColorScheme.
//
// Ownership: the file <data>/color-schemes/HorneroSignal.colors and the key
// [UiSettings] ColorScheme (marker: its value HorneroSignal). Every other
// kdeglobals group and key is preserved. Policy key: kdeConsumer.

pub const kde_scheme_id = 'HorneroSignal'
const kde_marker = '# hornero-managed: [UiSettings] ColorScheme (horneroctl appearance set-qt kde=off to opt out)'

pub fn kde_scheme_file() string {
	return os.join_path(xdg_or_home('XDG_DATA_HOME', '.local/share'), 'color-schemes', '${kde_scheme_id}.colors')
}

fn kde_globals_file() string {
	return os.join_path(gtk_config_home(), 'kdeglobals')
}

// kde_lib_dirs lists where KDE Frameworks colour libraries live.
// HORNERO_KDE_LIB_DIRS (colon separated) overrides for tests.
fn kde_lib_dirs() []string {
	override := os.getenv('HORNERO_KDE_LIB_DIRS')
	if override.len > 0 {
		return override.split(':').filter(it.len > 0)
	}
	return ['/usr/lib', '/usr/lib64']
}

// kde_present: KDE Frameworks colour support is installed (a KDE app such as
// Dolphin pulls it in) or the user already has a kdeglobals.
pub fn kde_present() bool {
	for d in kde_lib_dirs() {
		for lib in ['libKF6ColorScheme.so.6', 'libKF5ConfigWidgets.so.5'] {
			if os.is_file(os.join_path(d, lib)) {
				return true
			}
		}
	}
	return os.is_file(kde_globals_file())
}

fn kde_rgb(hex string) string {
	r, g, b := qt_hex_rgb(hex)
	return '${r},${g},${b}'
}

// render_kde_colors renders a KDE .colors scheme from the live theme.
// Views sit on sunken, windows on base, buttons on raised; selection is the
// celeste cue, active/neutral the amber signal (RFC 0001 roles only).
pub fn render_kde_colors(t SignalTheme) string {
	groups := [
		['View', 'sunken', 'panel'],
		['Window', 'base', 'panel'],
		['Button', 'raised', 'lifted'],
		['Selection', 'cue', 'cueWell'],
		['Tooltip', 'lifted', 'raised'],
		['Complementary', 'ground', 'base'],
		['Header', 'base', 'panel'],
	]
	mut out := [
		'# Hornero Signal KDE colour scheme for ${t.id} (${t.mode}) - GENERATED by horneroctl; do not hand-edit.',
		'[General]',
		'Name=Hornero Signal',
		'ColorScheme=${kde_scheme_id}',
		'',
	]
	for g in groups {
		sel := g[0] == 'Selection'
		fg := if sel { 'onCue' } else { 'ink' }
		inactive := if sel { 'onCue' } else { 'inkMuted' }
		out << '[Colors:${g[0]}]'
		out << 'BackgroundNormal=${kde_rgb(t.role(g[1]))}'
		out << 'BackgroundAlternate=${kde_rgb(t.role(g[2]))}'
		out << 'ForegroundNormal=${kde_rgb(t.role(fg))}'
		out << 'ForegroundInactive=${kde_rgb(t.role(inactive))}'
		out << 'ForegroundActive=${kde_rgb(t.role('signal'))}'
		out << 'ForegroundLink=${kde_rgb(t.role('cue'))}'
		out << 'ForegroundVisited=${kde_rgb(t.role('inkMuted'))}'
		out << 'ForegroundNegative=${kde_rgb(t.role('alert'))}'
		out << 'ForegroundNeutral=${kde_rgb(t.role('signal'))}'
		out << 'ForegroundPositive=${kde_rgb(t.role('phosphor'))}'
		out << 'DecorationFocus=${kde_rgb(t.role('cue'))}'
		out << 'DecorationHover=${kde_rgb(t.role('cue'))}'
		out << ''
	}
	return out.join('\n')
}

// kde_set_scheme_key sets [UiSettings] ColorScheme, preserving everything else.
fn kde_set_scheme_key(text string) string {
	mut out := []string{}
	mut in_ui := false
	mut seen := false
	mut has_marker := false
	for line in text.split_into_lines() {
		s := line.trim_space()
		if s == kde_marker {
			has_marker = true
		}
		if s.starts_with('[') {
			in_ui = s == '[UiSettings]'
			out << line
			continue
		}
		if in_ui && s.starts_with('ColorScheme=') {
			out << 'ColorScheme=${kde_scheme_id}'
			seen = true
			continue
		}
		out << line
	}
	if !seen {
		idx := out.index('[UiSettings]')
		if idx >= 0 {
			out.insert(idx + 1, 'ColorScheme=${kde_scheme_id}')
		} else {
			if out.len > 0 && out.last().trim_space().len > 0 {
				out << ''
			}
			out << '[UiSettings]'
			out << 'ColorScheme=${kde_scheme_id}'
		}
	}
	if !has_marker {
		out.insert(0, kde_marker)
	}
	return out.join('\n') + '\n'
}

// kde_class: managed | unset | user-scheme.
fn kde_class(text string) string {
	v := qt_ini_value(text, 'UiSettings', 'ColorScheme')
	if v == kde_scheme_id {
		return 'managed'
	}
	return if v.len == 0 { 'unset' } else { 'user-scheme' }
}

// kde_sync renders the scheme and selects it in kdeglobals.
pub fn kde_sync(theme SignalTheme, dry_run bool) QtSyncReport {
	policy := qt_policy('kde')
	if policy == 'off' {
		return QtSyncReport{
			toolkit: 'kde'
			status:  'off'
			detail:  'opted out (kdeConsumer=off); files untouched'
		}
	}
	if !kde_present() {
		return QtSyncReport{
			toolkit: 'kde'
			status:  'not-installed'
			detail:  'no KDE Frameworks apps installed; nothing to theme'
		}
	}
	conf := kde_globals_file()
	has_conf := os.is_file(conf)
	existing := os.read_file(conf) or { '' }
	class := if has_conf { kde_class(existing) } else { 'fresh' }
	if class == 'user-scheme' && policy != 'force' {
		return QtSyncReport{
			toolkit: 'kde'
			status:  'user-palette'
			detail:  'your own KDE colour scheme (${qt_ini_value(existing, 'UiSettings', 'ColorScheme')}) is selected; left alone. Take over with: horneroctl appearance set-qt kde=force --yes'
		}
	}
	scheme_path := kde_scheme_file()
	rendered := render_kde_colors(theme)
	next := kde_set_scheme_key(existing)
	scheme_changed := (os.read_file(scheme_path) or { '' }) != rendered
	conf_changed := next != existing
	if !scheme_changed && !conf_changed {
		return QtSyncReport{
			toolkit: 'kde'
			status:  'unchanged'
			detail:  '${theme.id} (${theme.mode}) already applied to KDE apps'
		}
	}
	if dry_run {
		return QtSyncReport{
			toolkit: 'kde'
			status:  'synced'
			detail:  'would write ${scheme_path}' +
				if conf_changed { ' and select it in ${conf} (${class})' } else { '' }
			changed: true
		}
	}
	mut backup := ''
	if has_conf && conf_changed {
		backup = qt_backup('kde', conf) or {
			return QtSyncReport{
				toolkit: 'kde'
				status:  'error'
				detail:  err.msg()
			}
		}
	}
	write_file_atomic(scheme_path, rendered) or {
		return QtSyncReport{
			toolkit: 'kde'
			status:  'error'
			detail:  err.msg()
		}
	}
	if conf_changed {
		write_file_atomic(conf, next) or {
			return QtSyncReport{
				toolkit: 'kde'
				status:  'error'
				detail:  err.msg()
			}
		}
	}
	return QtSyncReport{
		toolkit: 'kde'
		status:  'synced'
		detail:  '${theme.id} (${theme.mode}) written to ${scheme_path}'
		changed: true
		backup:  backup
	}
}

// kde_doctor_check reports the KDE colour-scheme consumer read-only.
pub fn kde_doctor_check(live SignalTheme) DoctorCheck {
	policy := qt_policy('kde')
	if policy == 'off' {
		return DoctorCheck{
			name:   'qt-kde'
			ok:     true
			detail: 'opted out (kdeConsumer=off); Hornero never touches kdeglobals'
		}
	}
	if !kde_present() {
		return DoctorCheck{
			name:   'qt-kde'
			ok:     true
			detail: 'no KDE Frameworks apps installed'
		}
	}
	conf := kde_globals_file()
	text := os.read_file(conf) or { '' }
	class := kde_class(text)
	if class == 'user-scheme' {
		return DoctorCheck{
			name:   'qt-kde'
			ok:     true
			warn:   true
			detail: 'your own KDE colour scheme (${qt_ini_value(text, 'UiSettings', 'ColorScheme')}) is selected; not following Hornero. Take over: horneroctl appearance set-qt kde=force --yes'
		}
	}
	if class != 'managed' {
		return DoctorCheck{
			name:   'qt-kde'
			ok:     false
			detail: '${conf} selects no colour scheme; KDE apps (Dolphin) fall back to Breeze Light. Run: horneroctl appearance sync-qt --yes'
		}
	}
	if live.id.len == 0 {
		return DoctorCheck{
			name:   'qt-kde'
			ok:     false
			detail: 'cannot verify: live Signal scheme unreadable'
		}
	}
	if (os.read_file(kde_scheme_file()) or { '' }) != render_kde_colors(live) {
		return DoctorCheck{
			name:   'qt-kde'
			ok:     false
			detail: '${kde_scheme_file()} does not match the live theme ${live.id}; run: horneroctl appearance sync-qt --yes'
		}
	}
	return DoctorCheck{
		name:   'qt-kde'
		ok:     true
		detail: '${live.id} (${live.mode}) applied via ${kde_scheme_file()}'
	}
}
